"""Refresh the website's research figures from CSV and executed report tables."""
from pathlib import Path
import json
import sys
import numpy as np
import pandas as pd
from scipy import stats

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))
from wine_stats.data import load_wines
from wine_stats.generator import quality_distribution, rejection_sample
from wine_stats.split import split_wines


def main():
    df = load_wines(ROOT / 'data/raw')
    manifest = pd.read_csv(ROOT / 'data/processed/alcohol_quality_split.csv')
    pd.testing.assert_frame_equal(manifest, split_wines(df, seed=42))
    train = df.loc[manifest['split'].eq('train')]
    scores, probabilities = quality_distribution(train.alcohol, train.quality, 12., k=720)
    mean = scores @ probabilities
    tables = ROOT / 'reports/tables'
    comparison = pd.read_csv(tables / 'generator_real_metrics.csv').set_index('metric')
    freq = pd.read_csv(tables / 'generator_real_frequencies.csv')
    timing = pd.read_csv(tables / 'generator_methods_timing.csv').set_index('method')
    _, attempts = rejection_sample(scores, probabilities, 100000, seed=42)
    demo = {'alcohol': 12., 'unit': '% об.', 'qualities': scores.tolist(),
            'probabilities': probabilities.tolist(), 'mean': float(mean),
            'variance': float(((scores-mean)**2) @ probabilities)}
    round4 = lambda value: round(float(value), 4)
    generator = {
        'demo': demo,
        'convergence': pd.read_csv(tables / 'generator_convergence.csv').to_dict('records'),
        'realComparison': {
            'n': int(manifest['split'].eq('test').sum()),
            'tv': round4(.5 * (freq.real - freq.model).abs().sum()),
            'realMean': round4(comparison.loc['mean', 'real']),
            'modelMean': round4(comparison.loc['mean', 'model']),
            'realVariance': round4(comparison.loc['variance', 'real']),
            'modelVariance': round4(comparison.loc['variance', 'model']),
        },
        'rejection': {'acceptRateEmpirical': 100000 / attempts,
            'acceptRateTheory': float(1 / (len(probabilities) * probabilities.max())),
            'medianMsInverse': float(timing.loc['inverse_cdf', 'median_ms']),
            'medianMsRejection': float(timing.loc['rejection', 'median_ms'])},
    }
    red = df.loc[df.wine_type.eq('red')]
    white = df.loc[df.wine_type.eq('white')]
    welch = stats.ttest_ind(red.quality, white.quality, equal_var=False)
    ci = welch.confidence_interval()
    pooled = np.sqrt(((len(red)-1)*red.quality.var() + (len(white)-1)*white.quality.var()) / (len(df)-2))
    metric = lambda label, value: {'label': label, 'value': str(value)}
    correlations = [stats.pearsonr(part.alcohol, part.quality) for part in [red, white]]
    mw = stats.mannwhitneyu(red.volatile_acidity, white.volatile_acidity, alternative='two-sided')
    hypotheses = {
        'quality-color': {'pValue': welch.pvalue, 'pValueText': f'{welch.pvalue:.3g}',
            'metrics': [metric('Разность средних (красное − белое)', f'{red.quality.mean()-white.quality.mean():.4f}'),
                        metric('95% доверительный интервал', f'[{ci.low:.4f}; {ci.high:.4f}]'),
                        metric('Коэффициент d Коэна', f'{(red.quality.mean()-white.quality.mean())/pooled:.4f}')]},
        'alcohol-quality': {'pValue': None, 'pValueUpperBound': .05,
            'pValueText': f'Красное: {correlations[0].pvalue:.3g}; белое: {correlations[1].pvalue:.3g}',
            'conclusion': 'Положительная связь обнаружена внутри обоих типов вина. Корреляция не доказывает причинность.'},
        'acidity-color': {'pValue': float(mw.pvalue), 'pValueUpperBound': .05,
            'pValueText': f'{mw.pvalue:.3g}' if mw.pvalue else 'Меньше машинной точности float64',
            'conclusion': 'Гипотеза одинаковых распределений отвергается при alpha = 0,05. Причина различий этим не установлена.'},
    }
    variables = {}
    for key, col in [('quality', 'quality'), ('alcohol', 'alcohol'), ('acidity', 'volatile_acidity')]:
        x = df[col]
        if key == 'alcohol':
            items = [('Red mean', red[col].mean()), ('White mean', white[col].mean()),
                     ('Red variance', red[col].var()), ('White variance', white[col].var())]
        else:
            items = [('Mean', x.mean()), ('Median', x.median()), ('Variance', x.var()), ('Std. dev.', x.std())]
            items += [('Mode', x.mode().iloc[0]), ('Range', f'{x.min()}-{x.max()}')] if key == 'quality' else [('Skewness', stats.skew(x)), ('Kurtosis', stats.kurtosis(x))]
        variables[key] = {'statistics': [metric(label, f'{v:.4f}' if isinstance(v, (float, np.floating)) else v) for label, v in items]}
    payload = {'generator': generator, 'hypotheses': hypotheses, 'variables': variables}
    output = '''// Generated by scripts/export_site_data.py. Do not edit by hand.
(() => {
    const data = PAYLOAD;
    const lab = window.LABS.find(item => item.id === "lab-01");
    Object.assign(lab.generator, data.generator);
    lab.hypotheses.forEach(item => Object.assign(item, data.hypotheses[item.id] || {}));
    lab.variables.forEach(item => Object.assign(item, data.variables[item.id] || {}));
    lab.status = "Сборка Lab01";
})();
'''.replace('PAYLOAD', json.dumps(payload, ensure_ascii=False, indent=2, allow_nan=False))
    (ROOT / 'WebSite/research-data.js').write_text(output, encoding='utf-8')
    print('Обновлён WebSite/research-data.js')


if __name__ == '__main__':
    main()
